typer_mod = pytest.importorskip("typer")

from typer.testing import CliRunner  # noqa: E402
from cli.main import app  # noqa: E402

runner = CliRunner()


class TestNarrateCommand:

    def test_no_args_shows_error(self):
        result = runner.invoke(app, ["narrate"])
        assert result.exit_code == 1

    def test_role_summary_exits_ok_no_ollama(self):
        """Should exit 0 even without Ollama (partial result)."""
        result = runner.invoke(app, ["narrate", "--function", "engineering", "--role", "backend"])
        assert result.exit_code == 0

    def test_role_summary_json_parseable(self):
        result = runner.invoke(app, [
            "narrate", "--function", "engineering", "--role", "backend", "--format", "json"
        ])
        assert result.exit_code == 0
        data = json.loads(result.output)
        assert "role" in data or "ai_impact_level" in data

    def test_brief_exits_ok_no_ollama(self):
        result = runner.invoke(app, ["narrate", "--function", "engineering", "--brief"])
        assert result.exit_code == 0
