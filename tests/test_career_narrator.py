class TestSkillAdvice:

    def test_missing_skill_name_returns_error(self, skill_live):
        result = skill_live.execute("skill_advice", skill_name="")
        assert not result.ok

    def test_nonexistent_skill_returns_error(self, skill_live):
        result = skill_live.execute("skill_advice", skill_name="xyznonexistentskill12345")
        assert not result.ok
        assert "not found" in result.error.lower()

    def test_partial_when_ollama_down(self, skill_live):
        result = skill_live.execute("skill_advice", skill_name="python", current_level="mid")
        # Either error (skill not found) or partial (Ollama down)
        assert result.status in (SkillStatus.PARTIAL, SkillStatus.ERROR)

    def test_success_with_mocked_ollama(self, skill_mocked):
        # Find a real skill name in the taxonomy
        from core.taxonomy import TaxonomyLoader
        loader = TaxonomyLoader(_TAXONOMY)
        skills = loader.search_skills("system design")
        if not skills:
            pytest.skip("No 'system design' skill in taxonomy")
        skill_name = skills[0].name

        with patch.object(skill_mocked, "_call_ollama", return_value=_MOCK_NARRATIVE):
            result = skill_mocked.execute("skill_advice", skill_name=skill_name, current_level="mid")
        assert result.ok
        assert result.data["advice"] == _MOCK_NARRATIVE
        assert "skill" in result.data
        assert "ai_impact_rating" in result.data
        assert "current_level" in result.data
        assert result.data["current_level"] == "mid"


