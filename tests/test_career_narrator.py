class TestRoleSummary:

    def test_invalid_role_returns_error(self, skill_live):
        result = skill_live.execute("role_summary", function_id="engineering", role_id="nonexistent")
        assert not result.ok
        assert "not found" in result.error.lower()

    def test_missing_function_returns_error(self, skill_live):
        result = skill_live.execute("role_summary", function_id="", role_id="backend")
        assert not result.ok

    def test_partial_result_when_ollama_down(self, skill_live):
        result = skill_live.execute("role_summary", function_id="engineering", role_id="backend")
        assert result.status == SkillStatus.PARTIAL
        assert result.data is not None
        assert result.error is not None
        # Raw data still present
        assert "role" in result.data
        assert "ai_impact_level" in result.data
        assert "most_at_risk" in result.data
        assert "most_resilient" in result.data

    def test_success_result_with_mocked_ollama(self, skill_mocked):
        with patch.object(skill_mocked, "_call_ollama", return_value=_MOCK_NARRATIVE):
            result = skill_mocked.execute("role_summary", function_id="engineering", role_id="backend")
        assert result.ok
        assert result.data["narrative"] == _MOCK_NARRATIVE
        assert result.data["model"] == "test-model"
        assert "role" in result.data
        assert "avg_automation_risk" in result.data

    def test_narrative_is_string(self, skill_mocked):
        with patch.object(skill_mocked, "_call_ollama", return_value=_MOCK_NARRATIVE):
            result = skill_mocked.execute("role_summary", function_id="engineering", role_id="backend")
        assert isinstance(result.data["narrative"], str)
        assert len(result.data["narrative"]) > 0

    def test_raw_data_present_even_with_ollama(self, skill_mocked):
        with patch.object(skill_mocked, "_call_ollama", return_value=_MOCK_NARRATIVE):
            result = skill_mocked.execute("role_summary", function_id="engineering", role_id="backend")
        for key in ("role", "function", "ai_impact_level", "avg_automation_risk",
                    "most_at_risk", "most_resilient"):
            assert key in result.data, f"missing key: {key}"


