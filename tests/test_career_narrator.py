class TestOllamaChat:

    def test_raises_on_connection_refused(self):
        with pytest.raises(Exception):
            _ollama_chat("hello", "http://localhost:0", "test-model", timeout=2)

    def test_returns_string_on_success(self):
        mock_response = json.dumps({"message": {"content": "test response"}}).encode()
        mock_resp = MagicMock()
        mock_resp.read.return_value = mock_response
        mock_resp.__enter__ = lambda s: s
        mock_resp.__exit__ = MagicMock(return_value=False)

        with patch("urllib.request.urlopen", return_value=mock_resp):
            result = _ollama_chat("hello", "http://localhost:11434", "test-model")
        assert result == "test response"


